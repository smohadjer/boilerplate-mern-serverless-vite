import { useState, useEffect } from "react";
import { Link } from 'react-router';

import './home.css';

interface Item {
  id: string | number
  name: string
}

interface Cache {
  data?: Item[]
  dbData?: Item[]
}

const cache: Cache = {};

export default function Home() {
    const [data, setData] = useState<Item[]>(cache.data ?? [])
    const [dbData, setDbData] = useState<Item[]>(cache.dbData ?? [])
    const [dataError, setDataError] = useState<string>()
    const [dbError, setDbError] = useState<string>()
    const [isDataLoading, setIsDataLoading] = useState(!cache.data)
    const [isDbLoading, setIsDbLoading] = useState(!cache.dbData)

    useEffect(() => {
        if (!cache.data) {
            fetch('/api/json-server')
            .then((response) => {
                if (!response.ok) throw new Error('Could not load static fruit data')
                return response.json() as Promise<Item[]>
            })
            .then((json) => {
                setData(json);
                cache.data = json;
                setIsDataLoading(false)
            })
            .catch((error: unknown) => {
                setDataError(error instanceof Error ? error.message : 'Could not load static fruit data')
                setIsDataLoading(false)
            });
        }

        if (!cache.dbData) {
            fetch('/api/index')
            .then((response) => {
                if (!response.ok) throw new Error('MongoDB is unavailable')
                return response.json() as Promise<Item[]>
            })
            .then((json) => {
                setDbData(json);
                cache.dbData = json;
                setIsDbLoading(false)
            })
            .catch((error: unknown) => {
                setDbError(error instanceof Error ? error.message : 'MongoDB is unavailable')
                setIsDbLoading(false)
            });
        }
    }, []);

    const getList = (items: Item[]) => {
        return (
            <ul className="items">
            {
                items.map((item) => {
                    return <li key={item.id}>{item.id} {item.name}</li>
                })
            }
            </ul>
        )
    }

    return (
        <>
            <h1>Boilerplate for building SPAs with React and Vercel's serverless</h1>
            <p>
                The fruit list below is generated by React from JSON returned by{' '}
                <a href="/api/json-server">/api/json-server</a>.
            </p>
            <p><Link to="/contacts">Link to Contacts</Link></p>
            <div className="flex">
                <div>
                    <h2>Fruits rendered from API JSON</h2>
                    {isDataLoading
                        ? 'Loading...'
                        : dataError
                          ? dataError
                          : data.length
                            ? getList(data)
                            : 'No fruits found.'}
                </div>
                <div>
                    <h2>Fruits from MongoDB database</h2>
                    {isDbLoading
                        ? 'Loading...'
                        : dbError
                          ? dbError
                          : dbData.length
                            ? getList(dbData)
                            : 'No fruits found.'}
                </div>
            </div>
        </>
    )
}
