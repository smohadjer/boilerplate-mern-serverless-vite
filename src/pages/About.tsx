import { useEffect, useState } from 'react'

interface User {
  id: number
  name: string
  email: string
}

let cachedUsers: User[] | undefined

export default function About() {
  const [users, setUsers] = useState<User[]>(cachedUsers ?? [])
  const [error, setError] = useState<string>()
  const [isLoading, setIsLoading] = useState(!cachedUsers)

  useEffect(() => {
    if (cachedUsers) return

    fetch('/api/users')
      .then((response) => {
        if (!response.ok) throw new Error('Could not load users')
        return response.json() as Promise<User[]>
      })
      .then((data) => {
        cachedUsers = data
        setUsers(data)
        setIsLoading(false)
      })
      .catch((fetchError: unknown) => {
        setError(fetchError instanceof Error ? fetchError.message : 'Could not load users')
        setIsLoading(false)
      })
  }, [])

  return (
    <>
      <h1>About</h1>
      <p>
        This user list is generated by React from JSON returned by{' '}
        <a href="/api/users">/api/users</a>.
      </p>
      <h2>Users</h2>
      {isLoading ? (
        'Loading...'
      ) : error ? (
        error
      ) : users.length > 0 ? (
        <ul>
          {users.map((user) => (
            <li key={user.id}>
              {user.name} — <a href={`mailto:${user.email}`}>{user.email}</a>
            </li>
          ))}
        </ul>
      ) : (
        'No users found.'
      )}
    </>
  )
}

